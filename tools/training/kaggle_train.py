"""Train on a Kaggle GPU; held-out test frames never leave this machine.

push: zip the train/val splits, split report and training code into a private Kaggle dataset,
      then start a private GPU kernel that runs train.fit() on it.
pull: once the kernel completes, download best.pt and its training record and export Core ML here.

Needs Kaggle credentials: `kaggle auth login`, or a token from kaggle.com/settings/api saved to
~/.kaggle/access_token. GPU and internet in kernels need a phone-verified Kaggle account.
"""
import argparse
import json
import re
import tempfile
import time
import zipfile
from datetime import datetime, timezone
from importlib.metadata import version
from pathlib import Path
import train

CODE = Path(__file__).resolve().parent
KERNEL = '''"""ZombsRoyale detector training, generated by tools/training/kaggle_train.py."""
import json, os, shutil, subprocess, sys, zipfile
from pathlib import Path

CONFIG = json.loads(__CONFIG__)
subprocess.run([sys.executable, "-m", "pip", "install", "--quiet", "ultralytics==" + CONFIG["ultralytics"]], check=True)
reports = sorted(Path("/kaggle/input").rglob("dataset/split-report.json"))
if reports:  # Kaggle extracted the uploaded archive.
    bundle = reports[0].parent.parent
else:
    bundle = Path("/tmp/bundle")
    with zipfile.ZipFile(next(Path("/kaggle/input").rglob("bundle.zip"))) as archive:
        archive.extractall(bundle)
work = Path("/tmp/work")
shutil.copytree(bundle / "dataset", work / "dataset")  # Writable, and outside the saved kernel output.
sys.path.insert(0, str(bundle / "code"))
from dataset import LABELS
from train import fit
(work / "dataset" / "dataset.yaml").write_text(
    "path: " + json.dumps(str(work / "dataset")) + "\\ntrain: images/train\\nval: images/val\\nnames:\\n"
    + "".join("  %d: %s\\n" % (i, json.dumps(label)) for i, label in enumerate(LABELS)))
os.chdir(work)
fit(work / "dataset" / "dataset.yaml", Path("/kaggle/working/run"), CONFIG["epochs"], CONFIG["size"], 0,
    CONFIG["batch"], CONFIG["nominalBatch"])
'''


def connect():
    from kaggle.api.kaggle_api_extended import KaggleApi
    api = KaggleApi()
    api.authenticate()
    return api, api.get_config_value("username")


def stage_bundle(dataset: Path, archive: Path) -> None:
    """Zip train/val images and labels, the split report and the recipe code. Test frames are excluded."""
    root = dataset.parent
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_STORED) as bundle:
        for split in ("train", "val"):
            for kind in ("images", "labels"):
                for file in sorted((root / kind / split).iterdir()):
                    bundle.write(file, f"dataset/{kind}/{split}/{file.name}")
        bundle.write(root / "split-report.json", "dataset/split-report.json")
        for name in ("train.py", "dataset.py"):
            bundle.write(CODE / name, f"code/{name}")


def slug(text: str) -> str:
    """Kaggle slugs: lowercase letters, digits and hyphens, at most 50 characters."""
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:50].rstrip("-")


def kernel_source(config: dict) -> str:
    return KERNEL.replace("__CONFIG__", repr(json.dumps(config)))


def wait_until(check, describe: str, interval: int, limit: int):
    from requests import ConnectionError, Timeout
    deadline = time.monotonic() + limit
    while True:
        try:
            value = check()
        except (ConnectionError, Timeout) as error:  # Sleep or Wi-Fi changes here; Kaggle keeps running.
            print(f"Network error while waiting for {describe}; retrying ({type(error).__name__})", flush=True)
            value = None
        if value is not None:
            return value
        if time.monotonic() > deadline:
            raise SystemExit(f"Timed out waiting for {describe}")
        time.sleep(interval)


def push(args) -> None:
    from requests import HTTPError
    report_file = args.dataset.parent / "split-report.json"
    train.require_trainable(json.loads(report_file.read_text()))
    api, user = connect()
    dataset_ref = f"{user}/{slug('zombs-' + args.dataset.parent.name)}"
    kernel_ref = f"{user}/{slug('zombs-train-' + args.output.name)}"
    config = dict(epochs=args.epochs, size=args.size, batch=args.batch, nominalBatch=args.nominal_batch,
                  ultralytics=version("ultralytics"))
    with tempfile.TemporaryDirectory() as tmp:
        data, kernel = Path(tmp) / "data", Path(tmp) / "kernel"
        data.mkdir(); kernel.mkdir()
        try:
            api.dataset_status(dataset_ref)
            print(f"Reusing private dataset {dataset_ref}; dataset exports are immutable.")
        except HTTPError as error:
            if error.response is None or error.response.status_code not in (403, 404):
                raise
            stage_bundle(args.dataset, data / "bundle.zip")
            (data / "dataset-metadata.json").write_text(json.dumps(dict(
                title=dataset_ref.split("/")[1], id=dataset_ref, licenses=[dict(name="other")])))
            created = api.dataset_create_new(str(data), public=False, convert_to_csv=False)
            if created.error:
                raise SystemExit(f"Kaggle rejected the dataset: {created.error}")
        def ready():
            try:
                return "ready" if str(api.dataset_status(dataset_ref)).lower() == "ready" else None
            except HTTPError as error:  # A just-created dataset reads as forbidden until Kaggle registers it.
                if error.response is None or error.response.status_code not in (403, 404):
                    raise
        wait_until(ready, "the Kaggle dataset to finish processing", 10, 1800)
        (kernel / "zombs_train.py").write_text(kernel_source(config))
        (kernel / "kernel-metadata.json").write_text(json.dumps(dict(
            id=kernel_ref, title=kernel_ref.split("/")[1], code_file="zombs_train.py", language="python",
            kernel_type="script", is_private=True, enable_gpu=True, enable_internet=True,
            dataset_sources=[dataset_ref], competition_sources=[], kernel_sources=[], model_sources=[])))
        response = api.kernels_push(str(kernel), None, args.accelerator)
    if response.error or response.invalid_dataset_sources:
        raise SystemExit(f"Kaggle rejected the kernel: {response.error or response.invalid_dataset_sources}")
    record = dict(kernel=kernel_ref, dataset=dataset_ref, url=response.url, version=response.version_number,
                  accelerator=args.accelerator, config=config, splitReportSHA256=train.sha256(report_file),
                  pushedAt=datetime.now(timezone.utc).isoformat())
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "kaggle-run.json").write_text(json.dumps(record, indent=2) + "\n")
    print(f"Training on Kaggle: {response.url}")


def pull(args) -> None:
    run = json.loads((args.output / "kaggle-run.json").read_text())
    api, _ = connect()

    def finished():
        status = api.kernels_status(run["kernel"])
        name = status.status.name if hasattr(status.status, "name") else str(status.status)
        if name in ("COMPLETE", "ERROR", "CANCEL_ACKNOWLEDGED"):
            return name, status.failure_message
        if not args.wait:
            raise SystemExit(f"Kernel {run['kernel']} is {name}; pull again later or pass --wait")
        return None
    state, failure = wait_until(finished, "the Kaggle kernel", 60, 6 * 3600)
    output = args.output / "kaggle-output"
    api.kernels_output(run["kernel"], str(output), force=True)
    if state != "COMPLETE":
        raise SystemExit(f"Kernel ended {state}: {failure or 'see the log in ' + str(output)}")
    weights = next(output.rglob("run/best.pt"), None)
    if weights is None:
        raise SystemExit(f"No run/best.pt in the kernel output; see the log in {output}")
    train.export(weights, args.dataset, args.output)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    for name in ("push", "pull"):
        command = commands.add_parser(name)
        command.add_argument("dataset", type=Path, help="dataset.yaml of the exported snapshot")
        command.add_argument("output", type=Path, help="artifacts folder for this run")
    commands.choices["push"].add_argument("--epochs", type=int, default=100)
    commands.choices["push"].add_argument("--size", type=int, default=960)
    commands.choices["push"].add_argument("--batch", type=int, default=4)
    commands.choices["push"].add_argument("--nominal-batch", type=int, default=64,
                                          help="Batch each optimizer step emulates; set to --batch for small pilots")
    commands.choices["push"].add_argument("--accelerator", default="NvidiaTeslaT4")
    commands.choices["pull"].add_argument("--wait", action="store_true", help="Poll until the kernel finishes")
    args = parser.parse_args()
    push(args) if args.command == "push" else pull(args)


if __name__ == "__main__":
    main()
