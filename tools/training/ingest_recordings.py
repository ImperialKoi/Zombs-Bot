"""Bring ZombsRecorder matches into an annotation corpus.

init: start a corpus. Existing sessions can be symlinked in with their frozen split plan.
pull: take every new match from Kaggle (zombs-rec-* datasets) or this Mac's recorder folder, verify it,
      extract frames with zombs-extract, audit, freeze its whole-match split and queue frames for annotate.py.
plan: write a split plan for some modes, in the form dataset.py --split-plan expects.

Nothing here trains: training stays on Kaggle (kaggle_train.py).
"""
from __future__ import annotations
import argparse
import hashlib
import json
import os
import shutil
import subprocess
import tempfile
from datetime import datetime, timedelta, timezone
from pathlib import Path
from dataset import MODES, load_sessions

ROOT = Path(__file__).resolve().parents[2]
EXTRACTOR = ROOT / "ZombsRecorder" / ".build" / "release" / "zombs-extract"
LOCAL_RECORDINGS = Path.home() / "Library" / "Application Support" / "ZombsRecorder" / "matches"
SLUG_PREFIX = "zombs-rec-"
SPLITS = ("train", "val", "test")
ASSIGNMENTS, PLAN, QUEUE, LOG = "split-assignments.json", "split-plan.json", "annotation-queue.json", "ingest-log.json"
ANCHORS = 12  # Evenly spaced frames per match, as in the v2 Solo intake.
CLOCK_SLACK_SECONDS = 30  # Friends' Mac clocks can differ a little.


class IngestError(Exception):
    pass


def read_json(path: Path, default=None):
    return json.loads(path.read_text()) if path.exists() else default


def write_json(path: Path, value) -> None:
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(json.dumps(value, indent=2) + "\n")
    temporary.replace(path)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as file:
        for block in iter(lambda: file.read(4 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def match_id_from_slug(slug: str) -> str:
    """zombs-rec-2026-10-06t19-02-11z-4c1a9e → 2026-10-06T19-02-11Z-4C1A9E (IDs only use digits, T, Z and uppercase hex)."""
    return slug.removeprefix(SLUG_PREFIX).upper()


def parse_time(text: str) -> datetime:
    return datetime.fromisoformat(text.replace("Z", "+00:00"))


def same_game(start: datetime, end: datetime, assignments: dict) -> str | None:
    """A recording that overlaps another in time is usually the same game seen by a teammate. It must share that
    recording's split; otherwise test frames would be near-duplicates of training frames."""
    slack = CLOCK_SLACK_SECONDS
    for match, a in sorted(assignments.items()):
        if "start" in a and "end" in a:
            other_start, other_end = parse_time(a["start"]), parse_time(a["end"])
            if (start - other_end).total_seconds() <= slack and (other_start - end).total_seconds() <= slack:
                return match
    return None


def assign_split(match_id: str, mode: str, assignments: dict) -> str:
    """Fill each mode's missing splits first (train, val, test), then hash 70/15/15. Assignments never move."""
    present = {a["split"] for a in assignments.values() if a["mode"] == mode}
    for split in SPLITS:
        if split not in present:
            return split
    bucket = int(hashlib.sha256(match_id.encode()).hexdigest()[:8], 16) % 20
    return "train" if bucket < 14 else "val" if bucket < 17 else "test"


def plan_from(assignments: dict, modes: set[str], only: set[str] | None = None) -> dict:
    return {"modes": sorted(modes), "splits": {split: sorted(m for m, a in assignments.items()
                                                          if a["split"] == split and a["mode"] in modes and (only is None or m in only))
                                               for split in SPLITS}}


def evenly_spaced(count: int, picks: int) -> set[int]:
    if count <= 0 or picks <= 0:
        return set()
    if count == 1 or picks == 1:
        return {0}
    return {round(i * (count - 1) / (picks - 1)) for i in range(picks)}


def queue_entries(match_id: str, rows: list[dict], per_match: int) -> list[dict]:
    picked = sorted(evenly_spaced(len(rows), ANCHORS) | evenly_spaced(len(rows), per_match))
    start = rows[0]["timestamp"]
    return [{"matchID": match_id, "image": rows[i]["image"], "timeSeconds": rows[i]["timestamp"] - start} for i in picked]


def write_plan(corpus: Path, record: dict) -> None:
    """The plan over every mode in the corpus, for scene_coverage.py."""
    modes = {a["mode"] for a in record["assignments"].values()}
    if modes:
        write_json(corpus / PLAN, {**plan_from(record["assignments"], modes),
                                   "notes": "Generated by ingest_recordings.py from split-assignments.json on every pull; do not edit."})


def init(corpus: Path, seed: Path | None = None, seed_plan: Path | None = None) -> dict:
    if (corpus / ASSIGNMENTS).exists():
        raise IngestError(f"{corpus} already has {ASSIGNMENTS}")
    if bool(seed) != bool(seed_plan):
        raise IngestError("--seed and --seed-plan go together so seeded matches keep their frozen splits")
    corpus.mkdir(parents=True, exist_ok=True)
    record = {"assignments": {}, "rule": "Whole matches. Assigned from recording metadata before review: a recording overlapping "
                                          "another in time (a teammate's view of the same game) takes that recording's split; otherwise "
                                          "each mode's missing train/val/test split first, then sha256(matchID) 70/15/15. Never moved."}
    if seed:
        plan = json.loads(seed_plan.read_text())
        planned = {match: split for split, ids in plan["splits"].items() for match in ids}
        for session in load_sessions(seed):
            match = session["matchID"]
            if match not in planned:
                raise IngestError(f"{match} is not in {seed_plan}")
            target = os.path.realpath(session["directory"])  # Link the real folder, relative to the corpus's real path.
            (corpus / session["directory"].name).symlink_to(os.path.relpath(target, os.path.realpath(corpus)), target_is_directory=True)
            record["assignments"][match] = {"mode": session["mode"], "split": planned[match], "source": "seed"}
        record["seed"] = {"recordings": str(seed), "plan": str(seed_plan), "planSHA256": sha256(seed_plan)}
    write_json(corpus / ASSIGNMENTS, record)
    write_plan(corpus, record)
    write_json(corpus / QUEUE, {"scope": "ZombsRecorder matches; polygons pending", "frames": []})
    write_json(corpus / LOG, {"matches": {}, "problems": {}})
    return record


class KaggleSource:
    """Private zombs-rec-* datasets in the signed-in Kaggle account."""

    def __init__(self, api=None, owner: str | None = None):
        if api is not None:
            self.api, self.owner = api, owner
            return
        from kaggle_train import connect
        try:
            self.api, self.owner = connect()
        except SystemExit as error:  # The kaggle package exits instead of raising.
            raise IngestError(f"Kaggle sign-in failed ({error}); see docs/DATA_WORKFLOW.md §4") from None

    def refs(self) -> list[str]:
        refs = set()
        for page in range(1, 200):
            batch = self.api.dataset_list(mine=True, page=page) or []
            refs |= {d.ref for d in batch if d.ref.split("/")[-1].startswith(SLUG_PREFIX)}
            if not batch:
                break
        return sorted(refs)

    def download(self, ref: str, destination: Path) -> None:
        try:
            self.api.dataset_download_files(ref, path=str(destination), unzip=True, quiet=True)
        except Exception:
            # Kaggle can answer 404 for the zipped download of a dataset that is ready; single files still download.
            for leftover in destination.iterdir():
                shutil.rmtree(leftover) if leftover.is_dir() else leftover.unlink()
            for file in self.api.dataset_list_files(ref).files or []:
                self.api.dataset_download_file(ref, file.name, path=str(destination), quiet=True)

    def delete(self, ref: str) -> None:
        owner, slug = ref.split("/")
        self.api.dataset_delete(owner, slug, no_confirm=True)


def verify(folder: Path) -> dict:
    manifest = read_json(folder / "recording.json")
    if not manifest or manifest.get("complete") is not True:
        raise IngestError("recording.json is missing or not marked complete")
    if manifest.get("mode") not in MODES or not manifest.get("parts"):
        raise IngestError("recording.json has no valid mode or parts")
    for part in manifest["parts"]:
        path = folder / part["file"]
        if Path(part["file"]).name != part["file"] or not path.is_file():
            raise IngestError(f"{part['file']} is missing")
        if path.stat().st_size != part["bytes"] or sha256(path) != part["sha256"]:
            raise IngestError(f"{part['file']} does not match the size and SHA-256 in recording.json")
    return manifest


def candidates(local: Path | None, source: KaggleSource | None) -> dict[str, dict]:
    """matchID → where to get it. A finished copy on this Mac wins over a download."""
    found = {}
    if source:
        for ref in source.refs():
            found[match_id_from_slug(ref.split("/")[-1])] = {"ref": ref}
    if local and local.is_dir():
        for folder in sorted(local.iterdir()):
            manifest = read_json(folder / "recording.json")
            if manifest and manifest.get("complete") and all((folder / p["file"]).is_file() for p in manifest.get("parts", [])):
                upload = read_json(folder / "upload.json", {})
                ref = found.get(folder.name, {}).get("ref") or (upload.get("ref") if upload.get("ready") else None)
                found[folder.name] = {"ref": ref, "local": folder}
    return dict(sorted(found.items()))


def fetch(match: str, where: dict, raw: Path, source: KaggleSource | None) -> Path:
    folder = raw / match
    if (folder / "recording.json").exists():
        return folder  # An earlier pull already has it.
    raw.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(dir=raw, prefix=f".{match}-"))
    try:
        if "local" in where:
            for file in sorted(where["local"].iterdir()):
                if file.name == "recording.json" or file.name.startswith("part-"):
                    subprocess.run(["cp", "-c", str(file), str(staging / file.name)], check=True)  # APFS clone: no extra space.
        else:
            source.download(where["ref"], staging)
        manifests = list(staging.rglob("recording.json"))
        if len(manifests) != 1:
            raise IngestError("the download does not contain exactly one recording.json")
        manifests[0].parent.rename(folder)
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    return folder


def extract(recording: Path, output: Path, extractor: list[str], fps: float) -> list[dict]:
    output.mkdir(parents=True)
    # Low priority so extraction never competes with the game. nice(1) still runs the command where lowering
    # priority is not allowed; a preexec_fn calling os.nice failed outright in some sandboxed environments.
    nice = [shutil.which("nice"), "-n", "10"] if shutil.which("nice") else []
    result = subprocess.run([*nice, *extractor, str(recording), str(output), "--fps", str(fps)], capture_output=True, text=True)
    if result.returncode != 0:
        raise IngestError(f"zombs-extract failed: {result.stderr.strip() or result.returncode}")
    frames = [json.loads(line) for line in result.stdout.splitlines() if line.strip()]
    if not frames:
        raise IngestError("zombs-extract wrote no frames")
    return frames


def write_session(folder: Path, manifest: dict, frames: list[dict], recording_sha: str, ref: str | None, fps: float) -> list[dict]:
    """The same files ZombsAssistant's recorder writes, so annotate.py, dataset.py and the audit read it unchanged."""
    match, mode = manifest["matchID"], manifest["mode"]
    session = {"coordinateSystem": "viewport-normalized-top-left", "createdAt": manifest["createdAt"], "matchID": match, "mode": mode,
               "source": "zombs-recorder", "recordedBy": manifest.get("recordedBy", ""), "teammates": manifest.get("teammates", []),
               "recordingSHA256": recording_sha, "kaggleRef": ref, "extraction": {"tool": "zombs-extract", "fps": fps}}
    (folder / "session.json").write_text(json.dumps(session, indent=2, sort_keys=True) + "\n")
    rows = [{"height": f["height"], "image": f["image"], "matchID": match, "mode": mode, "part": f["part"],
             "timestamp": f["timestamp"], "width": f["width"]} for f in frames]
    (folder / "frames.jsonl").write_text("".join(json.dumps(row, sort_keys=True) + "\n" for row in rows))
    for name in ("observations.jsonl", "decisions.jsonl"):  # No perception ran; empty logs keep the audit consistent.
        (folder / name).write_text("")
    return rows


def audit_session(folder: Path) -> dict:
    from audit_recordings import audit
    with tempfile.TemporaryDirectory() as temporary:
        (Path(temporary) / folder.name).symlink_to(folder.resolve(), target_is_directory=True)
        return audit(Path(temporary))


def contact_sheet(folder: Path, rows: list[dict], output: Path, picks: int = 24, width: int = 480) -> None:
    from PIL import Image, ImageDraw
    thumbnails = []
    for index in sorted(evenly_spaced(len(rows), picks)):
        with Image.open(folder / rows[index]["image"]) as image:
            image.thumbnail((width, width))
            thumbnails.append((image.convert("RGB"), rows[index]["timestamp"] - rows[0]["timestamp"]))
    columns = 6
    w, h = thumbnails[0][0].size
    sheet = Image.new("RGB", (columns * w, -(-len(thumbnails) // columns) * h))
    draw = ImageDraw.Draw(sheet)
    for n, (image, seconds) in enumerate(thumbnails):
        x, y = n % columns * w, n // columns * h
        sheet.paste(image, (x, y))
        draw.text((x + 6, y + 4), f"{seconds:7.1f} s", fill=(255, 230, 0))
    output.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(output, quality=85)


def register(corpus: Path, match: str, mode: str, rows: list[dict], record: dict, queue: dict, per_match: int,
             start: datetime) -> tuple[str, int]:
    """Queue first, then freeze the split, so a run interrupted in between is repaired without duplicates."""
    queued = {(f["matchID"], f["image"]) for f in queue["frames"]}
    entries = [e for e in queue_entries(match, rows, per_match) if (e["matchID"], e["image"]) not in queued]
    queue["frames"].extend(entries)
    write_json(corpus / QUEUE, queue)
    end = start + timedelta(seconds=rows[-1]["timestamp"])
    twin = same_game(start, end, record["assignments"])
    split = record["assignments"][twin]["split"] if twin else assign_split(match, mode, record["assignments"])
    entry = {"mode": mode, "split": split, "source": "zombs-recorder", "start": start.isoformat(), "end": end.isoformat()}
    if twin:
        entry["sameGameAs"] = twin
    record["assignments"][match] = entry
    write_json(corpus / ASSIGNMENTS, record)
    return split, len(entries)


def pull(corpus: Path, *, raw: Path, extractor: list[str], fps: float = 5, per_match: int = 0, source: KaggleSource | None = None,
         local: Path | None = LOCAL_RECORDINGS, keep_video: bool = False, delete_remote: bool = False) -> dict:
    if delete_remote and not keep_video:
        raise IngestError("--delete-remote needs the local video kept, so one copy always survives")
    record = read_json(corpus / ASSIGNMENTS)
    if record is None:
        raise IngestError(f"Run `init {corpus}` first")
    log = read_json(corpus / LOG, {"matches": {}, "problems": {}})
    queue = read_json(corpus / QUEUE, {"scope": "ZombsRecorder matches; polygons pending", "frames": []})
    staging = corpus / ".staging"  # Not a session folder: load_sessions only looks one level down.
    summary = {"ingested": [], "skipped": [], "problems": {}, "warnings": []}
    for match, where in candidates(local, source).items():
        if match in record["assignments"]:
            summary["skipped"].append(match)
            continue
        if (corpus / match).exists():  # Moved in by an interrupted run but never registered.
            session = read_json(corpus / match / "session.json")
            rows = [json.loads(line) for line in (corpus / match / "frames.jsonl").read_text().splitlines() if line]
            split, queued = register(corpus, match, session["mode"], rows, record, queue, per_match, parse_time(session["createdAt"]))
            summary["ingested"].append({"matchID": match, "mode": session["mode"], "split": split, "frames": len(rows), "queued": queued})
            continue
        try:
            recording = fetch(match, where, raw, source)
            manifest = verify(recording)
            if manifest["matchID"] != match:
                raise IngestError(f"recording.json describes {manifest['matchID']}")
            shutil.rmtree(staging / match, ignore_errors=True)
            frames = extract(recording, staging / match, extractor, fps)
            rows = write_session(staging / match, manifest, frames, sha256(recording / "recording.json"), where.get("ref"), fps)
            report = audit_session(staging / match)
            report["recordingsRoot"] = str(corpus.resolve())
            (corpus / "audits").mkdir(exist_ok=True)
            write_json(corpus / "audits" / f"{match}.json", report)
            if not report["passed"]:
                raise IngestError(f"audit failed: {report['sessions'][0]['errors'][:3]}")
            (staging / match).rename(corpus / match)
        except Exception as error:  # One bad match must not stop the others.
            shutil.rmtree(staging / match, ignore_errors=True)
            summary["problems"][match] = log["problems"][match] = f"{now()}: {error}"
            write_json(corpus / LOG, log)
            continue
        split, queued = register(corpus, match, manifest["mode"], rows, record, queue, per_match, parse_time(manifest["createdAt"]))
        try:
            contact_sheet(corpus / match, rows, corpus / "contact-sheets" / f"{match}.jpg")
        except Exception as error:
            summary["warnings"].append(f"{match}: no contact sheet ({error})")
        video_kept = keep_video or not where.get("ref")
        if not video_kept:
            for part in manifest["parts"]:
                (recording / part["file"]).unlink(missing_ok=True)
        remote_deleted = False
        if delete_remote and where.get("ref"):
            try:
                source.delete(where["ref"])
                remote_deleted = True
            except Exception as error:
                summary["warnings"].append(f"{match}: Kaggle dataset not deleted ({error})")
        log["problems"].pop(match, None)
        log["matches"][match] = {"mode": manifest["mode"], "recordedBy": manifest.get("recordedBy", ""), "split": split,
                                 "source": "local" if "local" in where else "kaggle", "kaggleRef": where.get("ref"),
                                 "raw": str(recording), "frames": len(rows), "fps": fps, "queued": queued,
                                 "durationSeconds": rows[-1]["timestamp"], "videoKept": video_kept,
                                 "remoteDeleted": remote_deleted, "ingestedAt": now()}
        write_json(corpus / LOG, log)
        summary["ingested"].append({"matchID": match, "mode": manifest["mode"], "split": split, "frames": len(rows), "queued": queued})
    write_plan(corpus, record)
    shutil.rmtree(staging, ignore_errors=True)
    return summary


def prune_video(corpus: Path, remote: dict[str, str] | None, everything: bool = False) -> dict:
    """Delete downloaded video of ingested matches; frames stay. Without `everything`, a video is only deleted
    when Kaggle holds a copy (`remote` maps match IDs to their Kaggle datasets)."""
    log = read_json(corpus / LOG, {"matches": {}, "problems": {}})
    summary = {"deleted": [], "kept": [], "freedBytes": 0}
    for match, entry in sorted(log["matches"].items()):
        parts = sorted(Path(entry["raw"]).glob("part-*.mov")) if entry.get("raw") else []
        if not parts:
            continue
        if not everything and match not in (remote or {}):
            summary["kept"].append(match)
            continue
        for part in parts:
            summary["freedBytes"] += part.stat().st_size
            part.unlink()
        entry["videoKept"] = False
        if remote and match in remote:
            entry["kaggleRef"] = remote[match]
        summary["deleted"].append(match)
    write_json(corpus / LOG, log)
    return summary


def emit_plan(corpus: Path, modes: set[str], output: Path, annotated_only: bool = False) -> dict:
    record = read_json(corpus / ASSIGNMENTS)
    if record is None:
        raise IngestError(f"{corpus} has no {ASSIGNMENTS}")
    only = None
    if annotated_only:
        only = {s["matchID"] for s in load_sessions(corpus) if any(r["annotation_path"].exists() for r in s["frames"])}
    plan = {**plan_from(record["assignments"], modes, only), "assignments": str(corpus / ASSIGNMENTS),
            "assignmentsSHA256": sha256(corpus / ASSIGNMENTS)}
    write_json(output, plan)
    return plan


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    start = commands.add_parser("init", help="create a corpus, optionally seeded with existing sessions")
    start.add_argument("corpus", type=Path)
    start.add_argument("--seed", type=Path, help="existing recordings root to symlink in")
    start.add_argument("--seed-plan", type=Path, help="that root's frozen split plan")
    get = commands.add_parser("pull", help="ingest new matches from Kaggle and this Mac")
    get.add_argument("corpus", type=Path)
    get.add_argument("--raw", type=Path, help="where downloaded recordings are kept (default: recorder-raw beside the corpus)")
    get.add_argument("--fps", type=float, default=5, help="frames per second to extract (default 5, like ZombsAssistant)")
    get.add_argument("--per-match", type=int, default=0, help=f"queue this many evenly spaced frames per match besides the {ANCHORS} anchors")
    get.add_argument("--extractor", type=Path, default=EXTRACTOR)
    get.add_argument("--no-kaggle", action="store_true", help="only take finished recordings from this Mac")
    get.add_argument("--no-local", action="store_true", help="only take matches from Kaggle")
    get.add_argument("--keep-video", action="store_true",
                     help="keep downloaded video after extracting frames (default: delete it once Kaggle holds a copy)")
    get.add_argument("--delete-remote", action="store_true", help="delete each Kaggle dataset after ingesting (needs --keep-video)")
    prune = commands.add_parser("prune-video", help="delete downloaded video of ingested matches (frames stay)")
    prune.add_argument("corpus", type=Path)
    prune.add_argument("--all", action="store_true", help="also delete video that Kaggle does not hold")
    emit = commands.add_parser("plan", help="write a split plan for dataset.py --split-plan")
    emit.add_argument("corpus", type=Path)
    emit.add_argument("--modes", nargs="+", choices=sorted(MODES), required=True)
    emit.add_argument("--annotated-only", action="store_true", help="only matches with annotations (release exports)")
    emit.add_argument("-o", "--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        if args.command == "init":
            record = init(args.corpus, args.seed, args.seed_plan)
            print(json.dumps({"corpus": str(args.corpus), "seededMatches": len(record["assignments"])}))
        elif args.command == "prune-video":
            remote = None if args.all else {match_id_from_slug(r.split("/")[-1]): r for r in KaggleSource().refs()}
            summary = prune_video(args.corpus, remote, args.all)
            print(json.dumps({"deleted": len(summary["deleted"]), "keptWithoutKaggleCopy": summary["kept"],
                              "freedGB": round(summary["freedBytes"] / 1e9, 2)}))
        elif args.command == "plan":
            plan = emit_plan(args.corpus, set(args.modes), args.output, args.annotated_only)
            print(json.dumps({"plan": str(args.output), **{k: len(v) for k, v in plan["splits"].items()}}))
        else:
            if not args.extractor.is_file():
                raise IngestError(f"{args.extractor} not found. Build it: bash ZombsRecorder/scripts/swift.sh build -c release --product zombs-extract")
            summary = pull(args.corpus, raw=args.raw or args.corpus.parent / "recorder-raw", extractor=[str(args.extractor)], fps=args.fps,
                           per_match=args.per_match, source=None if args.no_kaggle else KaggleSource(),
                           local=None if args.no_local else LOCAL_RECORDINGS, keep_video=args.keep_video,
                           delete_remote=args.delete_remote)
            for match in summary["ingested"]:
                print(f"ingested {match['matchID']} ({match['mode']} → {match['split']}): {match['frames']} frames, {match['queued']} queued")
            for match, problem in summary["problems"].items():
                print(f"problem  {match}: {problem}")
            for warning in summary["warnings"]:
                print(f"warning  {warning}")
            queued = len(read_json(args.corpus / QUEUE)["frames"])
            print(f"{len(summary['ingested'])} new, {len(summary['skipped'])} already ingested; {queued} frames in {args.corpus / QUEUE}")
            if summary["ingested"]:
                print(f"Annotate: python3 tools/training/annotate.py {args.corpus} --queue {args.corpus / QUEUE}")
            raise SystemExit(2 if summary["problems"] else 0)
    except IngestError as error:
        raise SystemExit(f"error: {error}")


